// доданок a(n-1) переходить в a(n): домножується на коефіцієнт рекурентності
// a(n) / a(n-1) = -(2n - 1) / ((2n + 1) x^2)
void nsDod::dod()
{
    a *= -(2.0 * n - 1) / ((2 * n + 1) * x * x);
}
